import type { Topic } from './topics';

/**
 * First-aid courses shown in the game.
 * - `sponsored`: partner courses promoted in the lobby pop-up (demo partners, made-up data).
 * - the others: real courses in TP.HCM (public info collected 11/2026, see "Nội dung game
 *   Lifesim_Dev-2.pdf" and "hub.pdf"); "Đăng ký học" opens the provider's official page.
 * - `isNew`: the SSVN catalogue listed as "Khoá mới nhất" in hub.pdf.
 */
export type Course = {
  id: string;
  /** Short label for the pop-up list. */
  tab: string;
  title: string;
  partner: string;
  tagline: string;
  description: string;
  highlights: string[];
  /** 'Trực tiếp' | 'Trực tuyến' | 'Kết hợp' – also used by the Hub filter. */
  mode: 'Trực tiếp' | 'Trực tuyến' | 'Kết hợp';
  format: string;
  duration: string;
  schedule: string;
  address?: string;
  price: string;
  /** Lowest fee in VND, for the budget filter (0 = free, null = fee not announced). */
  priceVnd: number | null;
  /** Old price, shown struck through when there is an offer. */
  oldPrice?: string;
  /** Extra line under the price (offers). */
  priceNote?: string;
  /** Banner colour. */
  tone: string;
  topics: Topic[];
  /** Topic drawn on the card when there is no banner image. */
  cover: Topic;
  /** Banner image (public path). */
  banner?: string;
  /** Provider's official page, opened by "Đăng ký học". */
  url?: string;
  sponsored?: boolean;
  /** Who the course is for ("Đối tượng"). */
  audience?: string;
  /** Listed under "Khoá mới nhất" – shown first in the Hub with a "Mới" badge. */
  isNew?: boolean;
};

